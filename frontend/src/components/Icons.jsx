/**
 * Returns a styled, professional SVG icon for a given notification type.
 */
export function getNotificationSvg(type, size = 18) {
  switch (type) {
    case "SLA_BREACHED":
      return <AlertOctagonIcon size={size} color="#dc2626" />;
    case "SLA_WARNING":
      return <AlertTriangleIcon size={size} color="#d97706" />;
    case "SLA_MET":
      return <CheckCircle2Icon size={size} color="#16a34a" />;
    case "ESCALATION":
      return <TrendingUpIcon size={size} color="#dc2626" />;
    case "INCIDENT_ASSIGNED":
      return <WrenchIcon size={size} color="#2563eb" />;
    case "INCIDENT_CREATED":
      return <TicketIcon size={size} color="#2563eb" />;
    case "STATUS_CHANGED":
      return <RefreshCwIcon size={size} color="#0284c7" />;
    case "COMMENT_ADDED":
      return <MessageSquareIcon size={size} color="#7c3aed" />;
    case "INCIDENT_ARCHIVED":
      return <ArchiveIcon size={size} color="#64748b" />;
    case "INCIDENT_MERGED":
      return <GitMergeIcon size={size} color="#9333ea" />;
    case "AVAILABILITY_CHANGED":
      return <ClockIcon size={size} color="#0284c7" />;
    case "WORKLOAD_WARNING":
      return <AlertTriangleIcon size={size} color="#d97706" />;
    case "INCIDENT_UPDATED":
      return <Edit3Icon size={size} color="#2563eb" />;
    default:
      return <InfoIcon size={size} color="#64748b" />;
  }
}
